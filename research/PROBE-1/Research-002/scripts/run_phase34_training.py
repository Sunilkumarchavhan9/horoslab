"""
HOROS PROBE-1 — Research-002: Phase 3.4.2–3.4.5 Full Model Training & Calibration Runner

Reads ONLY the archived Phase 3.4 datasets (generated by prepare_phase34_datasets.py),
verifies SHA-256 dataset checksums and zero train/calib/eval seed overlap, trains
B1 (MSE), B2 (Gaussian NLL), B3 (E=5 bootstrapped ensemble + per-member checkpoints),
and calibrates B4 (ContactStratifiedConformalWM + APS + Episode + MultiHorizon) per
(task, condition) using shared per-task z-score standardization (fitted on M0+M4 train
splits only) and uniform global gradient clipping (max_grad_norm = 1.0).

GATED: Executed only after Phase 3.4.1 remediation review approval.
"""

from __future__ import annotations
import json
import os
import sys

current_dir = os.path.dirname(os.path.abspath(__file__))
r002_root = os.path.abspath(os.path.join(current_dir, ".."))
repo_root = os.path.abspath(os.path.join(r002_root, "..", "..", ".."))
if r002_root not in sys.path:
    sys.path.insert(0, r002_root)
if os.path.join(r002_root, "src") not in sys.path:
    sys.path.insert(0, os.path.join(r002_root, "src"))

from src.integrated.phase34_pipeline import (
    PHASE34_B4_MIN_STRATUM_SAMPLES,
    PHASE34_TASKS,
    Phase34TrainingPipeline,
    _sha256_file,
    load_phase34_dataset_bundle,
)
from src.integrated.calibration_runner import PRIMARY_ALPHA, verify_disjoint_seed_pools
from src.integrated.statistical_analysis import to_json_serializable


def expected_checkpoint_layout(checkpoint_root: str) -> dict:
    """Returns canonical expected Phase 3.4 checkpoint paths for both tasks & conditions."""
    layout = {}
    for task in PHASE34_TASKS:
        layout[task] = {}
        for cond in ("M0_passive", "M4_acmm"):
            cond_dir = os.path.join(checkpoint_root, task, cond)
            layout[task][cond] = {
                "B1": os.path.join(cond_dir, "b1_deterministic.pt"),
                "B2": os.path.join(cond_dir, "b2_probabilistic.pt"),
                "B3_ensemble": os.path.join(cond_dir, "b3_ensemble.pt"),
                "B3_members": [os.path.join(cond_dir, f"b3_member_{i}.pt") for i in range(5)],
                "B4_calibration": os.path.join(cond_dir, "b4_conformal_calibration.json"),
            }
    return layout


def run_phase34_training_and_calibration(
    dataset_dir: str = None,
    manifest_path: str = None,
    checkpoint_root: str = None,
    report_path: str = None,
) -> dict:
    dataset_dir = dataset_dir or os.path.join(r002_root, "datasets", "phase3_4")
    manifest_path = manifest_path or os.path.join(r002_root, "manifests", "phase34_dataset_manifest.json")
    checkpoint_root = checkpoint_root or os.path.join(r002_root, "checkpoints", "phase3_4")
    report_path = report_path or os.path.join(checkpoint_root, "phase34_training_report.json")

    verify_disjoint_seed_pools()
    with open(manifest_path, "r", encoding="utf-8") as f:
        manifest = json.load(f)
    manifest_sha = _sha256_file(manifest_path)

    pipeline = Phase34TrainingPipeline(
        checkpoint_root=checkpoint_root,
        hidden_dim=64,
        epochs=45,
        lr=2e-3,
        max_grad_norm=1.0,
        alpha=PRIMARY_ALPHA,
        min_stratum_samples=PHASE34_B4_MIN_STRATUM_SAMPLES,
        seed=42,
    )

    tasks_report = {}
    for task in PHASE34_TASKS:
        m0_info = manifest["splits"][f"{task}__M0_passive"]
        m4_info = manifest["splits"][f"{task}__M4_acmm"]
        cal_info = manifest["splits"][f"{task}__calibration"]

        m0_path = os.path.join(dataset_dir, m0_info["npz_filename"])
        m4_path = os.path.join(dataset_dir, m4_info["npz_filename"])
        cal_path = os.path.join(dataset_dir, cal_info["npz_filename"])

        for p, info in ((m0_path, m0_info), (m4_path, m4_info), (cal_path, cal_info)):
            if _sha256_file(p) != info["sha256"]:
                raise RuntimeError(f"Checksum mismatch for dataset bundle {p}.")

        m0_bundle = load_phase34_dataset_bundle(m0_path)
        m4_bundle = load_phase34_dataset_bundle(m4_path)
        cal_bundle = load_phase34_dataset_bundle(cal_path)

        tasks_report[task] = pipeline.train_and_calibrate_task(
            task=task,
            m0_bundle=m0_bundle,
            m4_bundle=m4_bundle,
            calib_bundle=cal_bundle,
            calib_manifest_sha256=manifest_sha,
            repo_root=repo_root,
        )

    master = {
        "stage": "Phase 3.4 Training & Conformal Calibration",
        "manifest_path": manifest_path,
        "manifest_sha256": manifest_sha,
        "expected_checkpoint_layout": expected_checkpoint_layout(checkpoint_root),
        "tasks": tasks_report,
    }
    os.makedirs(os.path.dirname(report_path), exist_ok=True)
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(to_json_serializable(master), f, indent=2, allow_nan=False)
    return master


if __name__ == "__main__":
    out = run_phase34_training_and_calibration()
    print("Phase 3.4 training & calibration completed:", list(out["tasks"].keys()))
